export const findIndustry = (slug: string) => INDUSTRIES.find((industry) => industry.slug === slug);

/** 이름·별칭에서 공백을 무시하고 찾는다. 이름에 걸린 것을 먼저 보여 준다. */
export function searchIndustries(query: string, limit = 8): IndustryExample[] {
  const q = query.replace(/\s+/g, "").toLowerCase();
  if (!q) return [];
  const squash = (s: string) => s.replace(/\s+/g, "").toLowerCase();
  const byName = INDUSTRIES.filter((i) => squash(i.name).includes(q));
  const byAlias = INDUSTRIES.filter((i) => !byName.includes(i) && i.aliases.some((a) => squash(a).includes(q)));
  return [...byName, ...byAlias].slice(0, limit);
}
